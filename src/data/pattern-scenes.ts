function layout(edges: string[], previous: string[] = [], focus: string[] = []): Scene {
  const ids = [...new Set(edges.flatMap(edge => edge.split(">")))];
  const existing = new Set(previous.flatMap(edge => edge.split(">")));
  const graph = new dagre.graphlib.Graph().setGraph({rankdir: "LR", nodesep: 36, ranksep: 64}).setDefaultEdgeLabel(() => ({}));
  ids.forEach(id => graph.setNode(id, {width: 146,height: 82}));
  edges.forEach(edge => {const [source,target] = edge.split(">"); graph.setEdge(source,target);});
  dagre.layout(graph);
  return {
    nodes: ids.map(id => {const point = graph.node(id); return {id,x: point.x - 73,y: point.y - 41, active: focus.includes(id) || previous.length > 0 && !existing.has(id)};}),
    edges: edges.map(edge => {const [source,target] = edge.split(">"); return {source,target,active: previous.length > 0 && !previous.includes(edge)};})
  };
}
export function getPatternScenes(slug: NewPatternSlug): [Scene,Scene,Scene,Scene] {
  const stages = topologies[slug];
  return stages.map((edges,index) => layout(edges,index > 0 ? stages[index - 1] : [], focuses[slug][index])) as [Scene,Scene,Scene,Scene];
}
